#!/usr/bin/env node
/* Cup Season — the Home-state fixtures, from the one source into the phone.
 *
 *   node tools/build-home-states.mjs
 *
 * `tests/fixtures/home-states.json` is the SOURCE (D259). The web reads it at
 * runtime with `fetch` — which is why the hatch cannot exist in production, as
 * `stamp-version.sh` publishes an allowlist and `tests/` is not on it. The
 * phone cannot fetch a repo file, so it gets this generated Swift twin instead,
 * wrapped in `#if DEBUG` so a Release build carries none of it.
 *
 * Generated, never hand-edited — the same rule as Tokens/Markers/Rpc
 * (CLAUDE.md). Preflight check 41 fails the push when it is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
export const SRC = join(root, 'tests', 'fixtures', 'home-states.json')
export const OUT = join(root, 'apps', 'ios', 'Packages', 'CupSeasonKit', 'Sources', 'CupSeasonKit', 'Generated', 'HomeStateFixtures.swift')

/** The generated Swift, as a string — so preflight 41 can compare it with what
 *  is on disk without running the generator over the file it is judging. */
export function render(doc) {

  /* A Swift multi-line string literal that cannot be broken by the JSON's own
     quotes: `#"""…"""#` raw-delimited, so nothing inside is an escape. */
  const raw = (s) => '#"""\n' + s + '\n"""#'
  const q = (s) => JSON.stringify(String(s))

  const states = doc.states.map(s => `    State(id: ${q(s.id)},
          matrix: ${q(s.matrix)},
          title: ${q(s.title)},
          note: ${q(s.note)},
          json: ${raw(JSON.stringify(s.payload))})`).join(',\n')

  return `// GENERATED by tools/build-home-states.mjs from tests/fixtures/home-states.json.
// DO NOT HAND-EDIT — regenerate. Preflight 41 fails the push when it is stale.
//
// The Home states of HOME_STATE_MATRIX.md §4, as payloads (D259 / IOS-040).
// Twelve of the seventeen states cannot be reached from any account this
// product has, which is why the re-audit could not photograph them; a fixture
// substituted for one read makes every one of them a screen a simulator can
// open. Nothing here is written to the server, and \`#if DEBUG\` means a Release
// build does not contain the strings at all.
//
// Dates are TOKENS, resolved at load: \`@today\`, \`@today+6\`, \`@today-3\` become
// calendar dates and \`@eyebrow+2\` becomes the dateline the day would wear. A
// fixture therefore never reads stale — the demo diorama's own rule.

#if DEBUG
import Foundation

public enum HomeStateFixtures {

  public struct State: Sendable, Identifiable, Equatable {
    /// The launch argument's word: \`-cs_dev_home_state <id>\`.
    public let id: String
    /// The row in \`HOME_STATE_MATRIX.md\` §4 this payload is the shape of.
    public let matrix: String
    public let title: String
    /// What the screenshot is evidence OF — including, where it applies, the
    /// fact that Home has no card for this state.
    public let note: String
    /// The payload verbatim, tokens unresolved.
    public let json: String
  }

  /// Every state, in the matrix's own order.
  public static let all: [State] = [
${states}
  ]

  public static func state(_ id: String) -> State? { all.first { $0.id == id } }

  /// The payload, tokens resolved and decoded. \`nil\` for an id nothing
  /// declares — the caller then loads the real read, which is the honest
  /// answer to a hatch nobody spelled correctly.
  public static func payload(_ id: String, today: String = CSDate.today()) -> HomeDispatch.Payload? {
    guard let s = state(id) else { return nil }
    guard let data = resolve(s.json, today: today).data(using: .utf8) else { return nil }
    return try? JSONDecoder().decode(HomeDispatch.Payload.self, from: data)
  }

  /// \`@today\`, \`@today±N\` and \`@eyebrow±N\`, resolved against one instant so
  /// every date in one payload agrees with every other.
  public static func resolve(_ json: String, today: String = CSDate.today()) -> String {
    var out = json
    let pattern = #"@(today|eyebrow)([+-][0-9]+)?"#
    guard let rx = try? NSRegularExpression(pattern: pattern) else { return out }
    let matches = rx.matches(in: out, range: NSRange(out.startIndex..., in: out)).reversed()
    for m in matches {
      guard let r = Range(m.range, in: out) else { continue }
      let kind = (Range(m.range(at: 1), in: out).map { String(out[$0]) }) ?? "today"
      let off = (Range(m.range(at: 2), in: out).flatMap { Int(out[$0]) }) ?? 0
      out.replaceSubrange(r, with: kind == "eyebrow" ? eyebrow(today, off) : day(today, off))
    }
    return out
  }

  static func day(_ today: String, _ offset: Int) -> String {
    guard let base = CSDate.local(today),
          let d = Calendar.current.date(byAdding: .day, value: offset, to: base) else { return today }
    return CSDate.iso(d)
  }

  /// "SAT · SEP 6" — a dateline eyebrow, in the record voice.
  static func eyebrow(_ today: String, _ offset: Int) -> String {
    CSDate.short(day(today, offset)).replacingOccurrences(of: ",", with: " ·").uppercased()
  }
}
#endif
`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const doc = JSON.parse(readFileSync(SRC, 'utf8'))
  writeFileSync(OUT, render(doc))
  console.log(`wrote ${OUT.slice(root.length)} — ${doc.states.length} state(s)`)
}
