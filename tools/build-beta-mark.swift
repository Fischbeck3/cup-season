let font = CGFont(CGDataProvider(url: fontURL as CFURL)!)!
func word(_ text: String, size: CGFloat, x: CGFloat, y: CGFloat, tracking: CGFloat) -> String {
  let ct = CTFontCreateWithGraphicsFont(font, size, nil, nil)
  var chars = Array(text.utf16), glyphs = [CGGlyph](repeating: 0, count: text.utf16.count)
  CTFontGetGlyphsForCharacters(ct, &chars, &glyphs, chars.count)
  var cursor = x, result = ""
  for glyph in glyphs {
    if let p = CTFontCreatePathForGlyph(ct, glyph, nil) {
      var transform = CGAffineTransform(a: 1, b: 0, c: 0, d: -1, tx: cursor, ty: y)
      p.copy(using: &transform)!.applyWithBlock { element in
        let e = element.pointee
        func point(_ i: Int) -> String { "\(e.points[i].x) \(e.points[i].y)" }
        switch e.type {
        case .moveToPoint: result += "M" + point(0)
        case .addLineToPoint: result += "L" + point(0)
        case .addQuadCurveToPoint: result += "Q" + point(0) + " " + point(1)
        case .addCurveToPoint: result += "C" + point(0) + " " + point(1) + " " + point(2)
        case .closeSubpath: result += "Z"
        @unknown default: break
        }
      }
    }
    var g = glyph, advance = CGSize.zero
    CTFontGetAdvancesForGlyphs(ct, .horizontal, &g, &advance, 1)
    cursor += advance.width + tracking
  }
  return result
}
