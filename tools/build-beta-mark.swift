func token(_ group: String, _ name: String) -> NSColor {
  let g = groups[group] as! [String: Any]
  let t = (g["tokens"] as! [String: Any])[name] as! [String: Any]
  let hex = t["dark"] as! String
  let n = UInt32(hex.dropFirst(), radix: 16)!
  return NSColor(srgbRed: CGFloat((n >> 16) & 255)/255, green: CGFloat((n >> 8) & 255)/255, blue: CGFloat(n & 255)/255, alpha: 1)
}
